/**
 * 수강증 원본 보관 기간 — **2개월** (2026-09-20 Alan "수강증보관은 두달동안해줘", 미확정 6 해결).
 *
 * 수강증에는 학생 **실명**이 찍혀 있다. 판정이 끝난 뒤에도 저장소에 남겨 둘 이유가 없으므로
 * 기간이 지나면 **파일만** 지우고 **기록(OCR 원문 · 판독 결과 · 승인/거절 사유)은 남긴다** —
 * 나중에 "왜 이 반에 배정됐나" 를 되짚을 수 있어야 하고, 위조 신호(같은 초 캡처 등)도 그 기록으로 잡는다.
 *
 * **아직 판정이 안 끝난 신청(`result is null`)은 지우지 않는다** — 스태프가 볼 그림이 사라지면 승인을 못 한다.
 * 대기 중인 건은 학생이 다시 올리면 `guardUpload` 가 지우므로 쌓이지 않는다 (도메인 규칙 4-2).
 */

/** 판정이 끝난 뒤 이 날수가 지나면 원본을 지운다. **학생 화면 문구(`RETENTION_LABEL`)와 같은 뜻이어야 한다.** */
export const RECEIPT_RETENTION_DAYS = 60;

/** 학생에게 보여 주는 말. 숫자를 바꾸면 여기도 같이 바꾼다 — 안 맞으면 고지한 것과 실제가 달라진다 */
export const RETENTION_LABEL = "2개월";

/**
 * 이 시각보다 **전에** 올라온 것이 삭제 대상이다.
 *
 * 기준을 `created_at` 으로 잡은 것은 `enrollment_verifications` 에 판정 시각 컬럼이 없어서다.
 * 승인·거절은 보통 하루 이틀 안에 나므로 실제로는 "판정 뒤 2개월" 과 거의 같고,
 * 어긋나더라도 **늦게 지우는 쪽**(더 오래 보관)이라 안전하다.
 */
export function purgeCutoff(now: Date = new Date()): string {
  return new Date(now.getTime() - RECEIPT_RETENTION_DAYS * 24 * 60 * 60 * 1000).toISOString();
}
