-- profiles
--   본인: 조회 + 전화번호만 수정 (name 은 수강증 대조 키, role 은 권한이라 잠근다)
--   스태프: 전체 조회. admin: 전체 수정
create policy "profiles: 본인 조회" on public.profiles
  for select to authenticated
  using ((select auth.uid()) = id);
create policy "profiles: 스태프 전체 조회" on public.profiles
  for select to authenticated
  using ((select private.is_staff()));
create policy "profiles: 본인 수정" on public.profiles
  for update to authenticated
  using ((select auth.uid()) = id)
  with check (
    (select auth.uid()) = id
    and role = (select private.user_role())
    and name = (select p.name from public.profiles p where p.id = (select auth.uid()))
  );
create policy "profiles: admin 수정" on public.profiles
  for update to authenticated
  using ((select private.is_admin()))
  with check ((select private.is_admin()));

