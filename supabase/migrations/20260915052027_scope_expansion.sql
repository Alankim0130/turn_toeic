-- ─── 7. 관리자 대시보드용 헬퍼 뷰 ──────────────────────────────────────────
-- 시간대별 인원수: 반(section) 단위로 현장 / 불라방 활성 수강생 수
create view public.section_headcounts
with (security_invoker = true) as
  select
    s.id as section_id,
    s.term_id,
    s.course_id,
    s.track,
    s.time_block,
    s.start_time,
    s.end_time,
    count(*) filter (where e.mode = 'onsite') as onsite_count,
    count(*) filter (where e.mode = 'live')   as live_count
  from public.class_sections s
  left join public.enrollments e
    on e.section_id = s.id and e.status = 'active'
  group by s.id;

grant select on public.section_headcounts to authenticated;
