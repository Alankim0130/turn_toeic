-- study_signups: 본인·스태프 조회. 신청·변경·취소는 신청 중(open)인 스터디에 그 달 수강생만
create policy "study_signups: 본인·스태프 조회" on public.study_signups
  for select to authenticated
  using ((select auth.uid()) = user_id or (select private.is_staff()));
create policy "study_signups: 수강생 신청" on public.study_signups
  for insert to authenticated
  with check (
    (select auth.uid()) = user_id
    and exists (
      select 1 from public.studies s
      where s.id = study_signups.study_id
        and s.status = 'open'
        and private.is_term_enrollee(s.term_id)
    )
  );
create policy "study_signups: 본인 시간대 변경" on public.study_signups
  for update to authenticated
  using ((select auth.uid()) = user_id)
  with check (
    (select auth.uid()) = user_id
    and exists (
      select 1 from public.studies s
      where s.id = study_signups.study_id
        and s.status = 'open'
        and private.is_term_enrollee(s.term_id)
    )
  );
create policy "study_signups: 본인 취소·스태프 정리" on public.study_signups
  for delete to authenticated
  using (
    (select private.is_staff())
    or (
      (select auth.uid()) = user_id
      and exists (select 1 from public.studies s where s.id = study_signups.study_id and s.status = 'open')
    )
  );

-- study_materials: 신청자는 수강 중이고 해당 날짜가 됐을 때만, 스태프는 전부. 비대면 스터디에만 등록
create policy "study_materials: 신청자·스태프 조회" on public.study_materials
  for select to authenticated
  using (
    (select private.is_staff())
    or (
      study_materials.date <= (select private.today_kst())
      and exists (
        select 1
        from public.study_signups g
        join public.studies s on s.id = g.study_id
        where g.study_id = study_materials.study_id
          and g.user_id = (select auth.uid())
          and private.has_term_access(s.term_id)
      )
    )
  );
create policy "study_materials: 스태프 등록" on public.study_materials
  for insert to authenticated
  with check (
    (select private.is_staff())
    and exists (select 1 from public.studies s where s.id = study_materials.study_id and s.kind = 'online')
  );
create policy "study_materials: 스태프 수정" on public.study_materials
  for update to authenticated
  using ((select private.is_staff()))
  with check (
    (select private.is_staff())
    and exists (select 1 from public.studies s where s.id = study_materials.study_id and s.kind = 'online')
  );
create policy "study_materials: 스태프 삭제" on public.study_materials
  for delete to authenticated using ((select private.is_staff()));

