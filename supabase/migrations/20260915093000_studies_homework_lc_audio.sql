-- ─── 1. RLS 헬퍼 ───────────────────────────────────────────────────────────

-- 그 달(term) 반에 배정된 수강생인가 — 스터디 신청 자격. 예비등록생(preliminary) 포함
create or replace function private.is_term_enrollee(p_term_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.enrollments e
    join public.enrollment_orders o on o.id = e.order_id
    join public.class_sections s on s.id = e.section_id
    where e.student_id = (select auth.uid())
      and s.term_id = p_term_id
      and e.status = 'active'
      and o.status in ('preliminary', 'active')
      and private.today_kst() <= s.closes_at
  )
$$;

-- 콘텐츠(비대면 자료·LC 음원) 열람 — has_section_access 의 기수 버전.
-- p_term_id 가 null 이면 "지금 수강 중인 반이 하나라도 있는가" (상시 공개 음원용)
create or replace function private.has_term_access(p_term_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select private.user_role() in ('student', 'instructor', 'admin')
     and exists (
       select 1
       from public.enrollments e
       join public.enrollment_orders o on o.id = e.order_id
       join public.class_sections s on s.id = e.section_id
       where e.student_id = (select auth.uid())
         and (p_term_id is null or s.term_id = p_term_id)
         and e.status = 'active'
         and o.status = 'active'
         and private.today_kst() <= s.closes_at
     )
$$;

grant execute on function
  private.is_term_enrollee(bigint),
  private.has_term_access(bigint)
to authenticated, service_role;

-- ─── 2. 스터디 ─────────────────────────────────────────────────────────────

create table public.studies (
  id          bigint generated by default as identity primary key,
  term_id     bigint not null references public.terms (id),
  kind        text not null check (kind in ('offline', 'online', 'vocab')),
  status      text not null default 'draft' check (status in ('draft', 'open', 'closed')),
  notice      text check (notice is null or char_length(notice) <= 1000),  -- 장소·요일·준비물 안내
  created_at  timestamptz not null default now(),
  unique (term_id, kind)
);
comment on table public.studies is '월별 스터디. kind: offline=대면, online=비대면, vocab=단어. status: draft 비공개 / open 신청 중 / closed 신청 마감';

-- 대면·단어 스터디 시간대. 강사가 그 달 편성 때 함께 정한다
create table public.study_slots (
  id             bigint generated by default as identity primary key,
  study_id       bigint not null references public.studies (id) on delete cascade,
  start_time     time not null,
  end_time       time not null,
  capacity       int check (capacity is null or capacity > 0),     -- null = 정원 없음
  applied_count  int not null default 0 check (applied_count >= 0),
  created_at     timestamptz not null default now(),
  check (end_time > start_time),
  unique (study_id, start_time),
  unique (id, study_id)                                             -- study_signups 복합 FK 대상
);
comment on column public.study_slots.applied_count is '신청 인원. study_signups 트리거가 유지한다 (직접 수정 불가)';

-- 스터디 신청. 한 스터디(유형)에 한 시간대만
create table public.study_signups (
  id          bigint generated by default as identity primary key,
  study_id    bigint not null references public.studies (id),     -- 신청자가 있는 스터디는 삭제 불가
  slot_id     bigint,                                              -- 대면·단어는 필수, 비대면은 null
  user_id     uuid not null references public.profiles (id) on delete cascade,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  unique (study_id, user_id),
  foreign key (slot_id, study_id) references public.study_slots (id, study_id)  -- 신청자가 있는 시간대는 삭제 불가
);
create index study_signups_user_id_idx on public.study_signups (user_id);
create index study_signups_slot_idx on public.study_signups (slot_id, study_id) where slot_id is not null;

-- 비대면 자료. 수업일마다 하루 하나
create table public.study_materials (
  id            bigint generated by default as identity primary key,
  study_id      bigint not null references public.studies (id),   -- 자료가 있는 스터디는 삭제 불가
  date          date not null,
  title         text check (title is null or char_length(title) <= 100),
  file_path     text not null unique,                              -- storage: study-materials/{study_id}/...
  file_name     text not null,                                     -- 원본 파일명 (다운로드 이름)
  file_size     bigint check (file_size is null or file_size >= 0),
  content_type  text,
  uploaded_by   uuid references public.profiles (id) on delete set null,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  unique (study_id, date)
