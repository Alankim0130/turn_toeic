--  * 파일은 전부 private 버킷. 다운로드는 서명 URL — storage 정책이 아래 테이블 RLS 를 그대로 따른다.
--  * 기존 study_applications(자유 양식·비회원 신청)는 운영 중인 main 코드가 아직 쓰므로 이번에
--    지우지 않는다. 새 신청은 study_signups 에 쌓이고, 배포 후 별도 마이그레이션으로 정리한다.
