-- ─── 5. 신청 트리거: 유형별 시간대 규칙 + 정원 ─────────────────────────────
-- applied_count 를 조건부로 올리므로 마지막 한 자리에 동시에 신청해도 정원을 넘지 않는다.
create or replace function private.study_signups_sync()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_kind text;
begin
  if tg_op <> 'DELETE' then
    select s.kind into v_kind from public.studies s where s.id = new.study_id;
    if (v_kind = 'online') <> (new.slot_id is null) then
      raise exception 'study_slot_rule'
        using errcode = '23514', detail = '비대면 스터디는 시간대 없이, 대면·단어 스터디는 시간대를 골라 신청합니다.';
    end if;
  end if;

  -- 시간대를 옮기거나 취소하면 이전 시간대 자리를 돌려준다
  if tg_op in ('UPDATE', 'DELETE') and old.slot_id is not null
     and (tg_op = 'DELETE' or new.slot_id is distinct from old.slot_id) then
    update public.study_slots
    set applied_count = greatest(applied_count - 1, 0)
    where id = old.slot_id;
  end if;

  -- 새 시간대는 정원 안에서만 차지한다
  if tg_op in ('INSERT', 'UPDATE') and new.slot_id is not null
     and (tg_op = 'INSERT' or new.slot_id is distinct from old.slot_id) then
    update public.study_slots
    set applied_count = applied_count + 1
    where id = new.slot_id
      and (capacity is null or applied_count < capacity);
    if not found then
      raise exception 'study_slot_full' using errcode = 'P0001', detail = '이 시간대는 정원이 찼습니다.';
    end if;
  end if;

  if tg_op = 'DELETE' then
    return old;
  end if;
  new.updated_at := now();
  return new;
end;
$$;

revoke execute on function private.study_signups_sync() from public, anon, authenticated;

create trigger study_signups_sync
  before insert or update or delete on public.study_signups
  for each row execute function private.study_signups_sync();

