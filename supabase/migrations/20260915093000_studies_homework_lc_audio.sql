-- ─── 8. 파일 저장소 (private bucket) ────────────────────────────────────────
-- 프로젝트 전역 업로드 한도가 50MB 라 버킷 한도도 그 안에서 잡는다.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values
  ('study-materials', 'study-materials', false, 50 * 1024 * 1024, null),               -- 스태프만 올림 (pdf·hwp·docx·zip 등)
  ('homework',        'homework',        false, 20 * 1024 * 1024, array['image/*', 'application/pdf']),
  ('lc-audio',        'lc-audio',        false, 50 * 1024 * 1024, array['audio/*'])
on conflict (id) do nothing;

-- study-materials: 조회는 study_materials 행을 볼 수 있는 사람(날짜 공개 규칙 포함), 쓰기는 스태프
create policy "study-materials: 신청자·스태프 조회" on storage.objects
  for select to authenticated
  using (
    bucket_id = 'study-materials'
    and (
      (select private.is_staff())
      or exists (select 1 from public.study_materials m where m.file_path = objects.name)
    )
  );
create policy "study-materials: 스태프 업로드" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'study-materials' and (select private.is_staff()));
create policy "study-materials: 스태프 수정" on storage.objects
  for update to authenticated
  using (bucket_id = 'study-materials' and (select private.is_staff()))
  with check (bucket_id = 'study-materials' and (select private.is_staff()));
create policy "study-materials: 스태프 삭제" on storage.objects
  for delete to authenticated
  using (bucket_id = 'study-materials' and (select private.is_staff()));

-- homework: 경로 규칙 homework/{auth.uid()}/{material_id}/{file}
create policy "homework: 본인 폴더 업로드" on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'homework'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );
create policy "homework: 본인·스태프 조회" on storage.objects
  for select to authenticated
  using (
    bucket_id = 'homework'
    and ((storage.foldername(name))[1] = (select auth.uid())::text or (select private.is_staff()))
  );
create policy "homework: 점검 전 본인 삭제" on storage.objects
  for delete to authenticated
  using (
    bucket_id = 'homework'
    and (storage.foldername(name))[1] = (select auth.uid())::text
    and not exists (
      select 1
      from public.homework_files f
      join public.homework_submissions s on s.id = f.submission_id
      where f.file_path = objects.name
        and s.status = 'checked'
    )
  );

-- lc-audio: 조회는 lc_audio_tracks 행을 볼 수 있는 사람, 쓰기는 스태프
