  add column enrollment_opens_at date,
  add column closes_at date,
  add constraint terms_closes_after_opens check (closes_at >= enrollment_opens_at);
comment on column public.terms.enrollment_opens_at is '그 달 개강일. 반 편성 달력에서 정하고 그 달 모든 반에 복사된다';
comment on column public.terms.closes_at is '그 달 종강일. 이 날이 지나면 다시보기가 닫힌다. 그 달 모든 반에 복사된다';

