-- 반 편성 달력 (2026-09-15 Alan 요청)
--
--  * 반 편성은 기수(월) 달력에서 한다. 강사가 [개강일][종강일][월수금][화목금][특강] 버튼을 고르고
--    날짜를 하나씩 눌러 찍은 뒤 "생성하기" → public.save_term_schedule() 한 번(한 트랜잭션)에 저장된다.
--  * 기수 단위 원천
--      terms.enrollment_opens_at / closes_at — 그 달 개강일·종강일 (그 달 모든 반에 공통)
--      term_class_dates                      — 그 달 월수금 / 화목금 수업일. 한 날짜는 한 트랙에만
--      special_lectures                      — 특강. 수업일과 같은 날이어도 되고 하루에 여러 개도 된다
--      lecturers                             — 특강 강사 선택지 (이혜영 · 이영수). 행을 추가하면 늘어난다
--  * 반(class_sections)의 개강일·종강일·session_dates 는 기수 달력에서 파생된다.
--    생성하기와 반 개설 때 private.sync_section_schedule() 이 맞춘다.
--    다시보기가 붙은 회차를 빼야 하면 저장 전체를 되돌린다 (미확정 4 확정 전까지 녹화본 보호).
--  * 반 편성 화면에서 수업 시작·종료 시간을 받지 않는다 → 시간 컬럼을 nullable 로 바꾼다.
--    컬럼은 지우지 않는다 (배포 중인 main 코드가 아직 읽는다).
-- ============================================================================

-- ─── 1. 기수: 개강일 · 종강일 ───────────────────────────────────────────────
