--
--  * 학생이 쓰는 교재(A/B)는 **듣는 시간대**로 정해진다. 같은 달에도 10:00 반은 A,
--    11:10 반은 B 를 쓰고, 다음 달에는 두 시간대가 서로 뒤바뀐다.
--    달의 홀짝으로 정하던 판정(`bookSetForMonth`)은 같은 달 학생의 절반에게 틀린다 —
--    "이번 달 교재" 표시뿐 아니라 수업일 달력이 어느 교재에 붙는지까지 어긋났다.
--  * 그래서 교재 세트를 반에 붙인다. 운영 데이터라 코드가 아니라 DB 에서 읽는다 (작업 원칙 4).
--  * 비워 두면 화면이 예전처럼 달 홀짝으로 짐작한다 — 기존 반이 갑자기 사라지지 않게.
-- ============================================================================

