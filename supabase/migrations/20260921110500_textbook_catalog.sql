-- ─── 1. 입금 계좌 ──────────────────────────────────────────────────────────
create table if not exists public.textbook_accounts (
  id          bigint generated by default as identity primary key,
  bank_name   text not null check (char_length(bank_name) between 1 and 30),
  account_no  text not null check (char_length(account_no) between 4 and 40),
  holder      text not null check (char_length(holder) between 1 and 30),
  label       text check (label is null or char_length(label) <= 40),   -- 예: "LC 교재비" — 계좌가 둘 이상일 때 가른다
  active      boolean not null default true,
  sort_order  int not null default 0,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

comment on table public.textbook_accounts is '교재비 입금 계좌 (강사가 등록). 학생 주문 화면에 금액과 함께 보인다';

-- ─── 2. 교재 ──────────────────────────────────────────────────────────────
create table if not exists public.textbook_items (
  id          bigint generated by default as identity primary key,
  name        text not null check (char_length(name) between 1 and 60),
  level       int references public.lc_levels (level),        -- null = 모든 레벨. 학생은 자기 레벨 교재만 본다
  price       int not null check (price between 0 and 1000000),
  account_id  bigint references public.textbook_accounts (id) on delete set null,  -- null = 기본 계좌
  note        text check (note is null or char_length(note) <= 200),
  active      boolean not null default true,
  sort_order  int not null default 0,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

comment on table public.textbook_items is '불라방 교재 (강사가 등록). level 이 비면 모든 레벨. 주문에는 이름·가격을 그 때의 값으로 박아 둔다';

-- ─── 3. 배송비·기본 계좌·안내 (한 줄) ──────────────────────────────────────
create table if not exists public.textbook_settings (
  id                 boolean primary key default true check (id),
  shipping_fee       int not null default 0 check (shipping_fee between 0 and 100000),
  default_account_id bigint references public.textbook_accounts (id) on delete set null,  -- 배송비·계좌를 안 고른 교재는 여기로
  notice             text check (notice is null or char_length(notice) <= 300),
  updated_at         timestamptz not null default now()
);

insert into public.textbook_settings (id) values (true) on conflict (id) do nothing;

-- ─── 4. 주문에 품목·금액·입금 정보를 박아 둔다 ────────────────────────────
alter table public.textbook_orders
  add column if not exists term_id        bigint references public.terms (id),
  add column if not exists items          jsonb not null default '[]'::jsonb,   -- [{id, name, price, account_id}] 주문한 때의 값
  add column if not exists items_total    int not null default 0,
  add column if not exists shipping_fee   int not null default 0,
  add column if not exists total_amount   int not null default 0,
  add column if not exists depositor_name text check (depositor_name is null or char_length(depositor_name) <= 30),
  add column if not exists pay_to         jsonb not null default '[]'::jsonb;   -- [{account_id, bank_name, account_no, holder, label, amount}]

comment on column public.textbook_orders.pay_to is '입금 안내 (주문한 때의 계좌·금액). 계좌를 바꿔도 지난 주문의 안내는 그대로다';

update public.textbook_orders o
   set term_id = s.term_id
  from public.class_sections s
 where s.id = o.section_id and o.term_id is null;

-- 한 달에 한 건 (취소한 것은 빼고)
create unique index if not exists textbook_orders_one_per_term
  on public.textbook_orders (user_id, term_id)
  where status <> 'cancelled' and term_id is not null;

-- ─── 5. 누가 읽고 쓰나 ────────────────────────────────────────────────────
-- 불라방 배정이 살아 있는 학생인가 (예비등록생 포함, 종강 전)
create or replace function private.has_live_enrollment()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
      from public.enrollments e
      join public.enrollment_orders o on o.id = e.order_id
      join public.class_sections s on s.id = e.section_id
     where e.student_id = (select auth.uid())
       and e.mode = 'live'
       and e.status = 'active'
       and o.status in ('preliminary', 'active')
       and private.today_kst() <= s.closes_at
  )
$$;

