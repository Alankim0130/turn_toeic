--   * **카탈로그·계좌를 DB 로** — 가격·계좌가 바뀌어도 배포가 필요 없다. 화면은 /admin/textbook-orders/setup (강사·관리자).
--   * **주문은 함수 하나로** (public.create_textbook_order) — 학생이 표에 직접 넣지 못한다.
--     품목·금액·입금 계좌는 **서버가 계산해 주문에 박아 둔다** (첫토익은 앱이 계산한 금액을 그대로 넣었다 — 공통 원칙 2).
--   * **한 달에 한 건** — (학생, 기수) 로 막는다. 주5일 학생이 월수금·화목금 반마다 두 번 주문하던 틈도 이것으로 닫힌다.
--   * **예비등록생도 주문한다** — 개강 전에 등업한 불라방 학생이 개강 전에 교재를 받아야 한다.
--   * 이 사이트는 결제를 **처리하지 않는다** — 계좌와 금액을 안내하고, 입금자명을 받고, 강사가 통장과 대조해 "입금 확인" 을 누른다.
--
--   계좌·교재 목록은 강사·관리자·조교와 **불라방 배정이 있는 학생만** 읽는다 (첫토익 12 — 계좌를 전체 공개로 열었던 사고).
