-- 입금 확인 전에는 본인이 취소한다
create or replace function public.cancel_textbook_order(p_id bigint)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.textbook_orders
     set status = 'cancelled', updated_at = now()
   where id = p_id
     and user_id = (select auth.uid())
     and status = 'requested';
  return found;
end;
$$;

