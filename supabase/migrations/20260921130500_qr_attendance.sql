  for select to authenticated using ((select private.is_crew()));

-- ─── 3. 30초마다 바뀌는 토큰 · 6자리 코드 ──────────────────────────────────
do $$
begin
  if not exists (select 1 from vault.secrets where name = 'attendance_qr_secret') then
    perform vault.create_secret(
      encode(extensions.gen_random_bytes(32), 'hex'),
      'attendance_qr_secret',
      'QR 출석 토큰(HMAC)의 비밀. 마이그레이션 20260921130500 이 DB 안에서 만들었다'
    );
  end if;
end;
$$;

-- 30초 칸 하나의 토큰(12자, QR 주소에 들어간다)과 6자리 코드(손으로 친다)
create or replace function private.attendance_token(p_step bigint)
returns table (token text, code text)
language sql
stable
security definer
set search_path = ''
as $$
  with h as (
    select encode(
             extensions.hmac(p_step::text, (select s.decrypted_secret from vault.decrypted_secrets s where s.name = 'attendance_qr_secret' limit 1), 'sha256'),
             'hex') as hex
  )
  select upper(substr(h.hex, 1, 12)),
         lpad(((('x' || substr(h.hex, 13, 8))::bit(32)::bigint) % 1000000)::text, 6, '0')
    from h
$$;

revoke all on function private.attendance_token(bigint) from public, anon, authenticated;

-- 교실 화면용: 지금 칸의 토큰·코드와 바뀌는 시각. 강사·관리자·조교만
create or replace function public.attendance_display()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_step bigint := floor(extract(epoch from now()) / 30)::bigint;
  t      record;
begin
  if not private.is_crew() then
    raise exception 'forbidden';
  end if;
  select * into t from private.attendance_token(v_step);
  return jsonb_build_object('token', t.token, 'code', t.code, 'expires_at', to_timestamp((v_step + 1) * 30));
end;
$$;

-- ─── 4. 오늘 교실에 와야 하는 내 반 ────────────────────────────────────────
-- 직접 배정 · 현장 · 인강 반 아님 · 수강 중(active) · 그 날 회차가 있음
create or replace function private.attendance_sessions(p_uid uuid, p_date date)
returns table (section_id bigint, label text, starts timestamp, ends timestamp)
language sql
stable
security definer
set search_path = ''
as $$
  select distinct
         s.id,
         concat_ws(' ', c.name, case s.track when 'mwf' then '월수금' else '화목금' end, s.time_block),
         p_date + private.time_block_start(s.time_block),
         p_date + private.time_block_end(s.time_block)
    from public.enrollments e
    join public.enrollment_orders o on o.id = e.order_id
    join public.class_sections s on s.id = e.section_id
    join public.courses c on c.id = s.course_id
    join public.session_dates d on d.section_id = s.id and d.date = p_date
   where e.student_id = p_uid
     and e.status = 'active'
     and o.status = 'active'
     and e.mode = 'onsite'
     and not s.recorded
     and p_date <= s.closes_at
     and private.time_block_start(s.time_block) is not null
     and private.time_block_end(s.time_block) is not null
$$;

revoke all on function private.attendance_sessions(uuid, date) from public, anon, authenticated;

-- ─── 5. 학생이 찍는다: 입실 · 퇴실 ─────────────────────────────────────────
-- 돌려주는 action: check_in · check_out · already_in · already_done · too_early · class_over ·
--                  no_class_today · live_student · recorded_day · not_started · bad_token · too_many · login_required
create or replace function public.attendance_scan(p_token text, p_method text default 'qr')
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid    uuid := (select auth.uid());
  v_now    timestamptz := now();
  v_kst    timestamp := now() at time zone 'Asia/Seoul';
  v_today  date := private.today_kst();
  v_step   bigint := floor(extract(epoch from now()) / 30)::bigint;
  v_in     text := upper(regexp_replace(coalesce(p_token, ''), '[^0-9A-Za-z]', '', 'g'));
  v_method text := case when p_method = 'code' then 'code' else 'qr' end;
  v_open   record;
  v_target record;
  v_next   timestamp;
  v_label  text;
  v_stay   int;
  v_id     bigint;
  v_late   boolean;
begin
  if v_uid is null then
    return jsonb_build_object('action', 'login_required');
  end if;

  -- 틀린 코드를 10분에 10번 넣으면 잠시 막는다 (6자리를 맞혀 보는 것을 막는다)
  if (select count(*) from public.attendance_events ev
       where ev.student_id = v_uid and ev.kind = 'reject' and ev.result = 'bad_token' and ev.created_at > v_now - interval '10 minutes') >= 10 then
    return jsonb_build_object('action', 'too_many');
  end if;

  -- 지금 칸과 앞 세 칸(2분)만 — 로그인을 거치는 동안 한두 번 바뀌어도 된다
  if v_in = '' or not exists (
    select 1
      from generate_series(v_step - 3, v_step) as g(step)
      cross join lateral private.attendance_token(g.step) t
     where t.token = v_in or t.code = v_in
  ) then
    insert into public.attendance_events (student_id, kind, method, result) values (v_uid, 'reject', v_method, 'bad_token');
    return jsonb_build_object('action', 'bad_token');
  end if;

  -- 오늘 교실에 올 반이 없으면 왜 없는지 알려 준다
  if not exists (select 1 from private.attendance_sessions(v_uid, v_today)) then
    return jsonb_build_object('action',
      case
        when exists (
          select 1 from public.enrollments e
            join public.enrollment_orders o on o.id = e.order_id
            join public.session_dates d on d.section_id = e.section_id and d.date = v_today
           where e.student_id = v_uid and e.status = 'active' and o.status = 'active' and e.mode = 'live') then 'live_student'
        when exists (
          select 1 from public.enrollments e
            join public.enrollment_orders o on o.id = e.order_id
            join public.class_sections s on s.id = e.section_id
            join public.session_dates d on d.section_id = s.id and d.date = v_today
           where e.student_id = v_uid and e.status = 'active' and o.status = 'active' and s.recorded) then 'recorded_day'
        when exists (select 1 from public.enrollment_orders o where o.user_id = v_uid and o.status = 'preliminary') then 'not_started'
        else 'no_class_today'
      end);
  end if;

  -- ① 퇴실: 오늘 입실만 한 기록 — 그 반 수업이 끝나고 30분까지
  select st.id, st.section_id, st.check_in_at, x.label
    into v_open
    from public.attendance_stamps st
    join private.attendance_sessions(v_uid, v_today) x on x.section_id = st.section_id
   where st.student_id = v_uid
     and st.class_date = v_today
     and st.status = 'in'
     and v_kst <= x.ends + interval '30 minutes'
   order by st.check_in_at desc
   limit 1;
  if found then
    v_stay := floor(extract(epoch from (v_now - v_open.check_in_at)) / 60)::int;
    if v_stay < 30 then
      return jsonb_build_object('action', 'already_in', 'label', v_open.label,
                                'at', to_char(v_open.check_in_at at time zone 'Asia/Seoul', 'HH24:MI'), 'stay', v_stay);
    end if;
    update public.attendance_stamps
       set status = 'out', check_out_at = v_now, updated_at = v_now
     where id = v_open.id and status = 'in';
    if not found then
      return jsonb_build_object('action', 'already_done', 'label', v_open.label);
    end if;
    insert into public.attendance_events (student_id, section_id, class_date, kind, method, result)
    values (v_uid, v_open.section_id, v_today, 'exit', v_method, 'check_out');
    return jsonb_build_object('action', 'check_out', 'label', v_open.label, 'at', to_char(v_kst, 'HH24:MI'), 'stay', v_stay);
  end if;

  -- ② 입실: 수업 시작 30분 전 ~ 끝, 아직 도장이 없는 반 중 가장 이른 것
  select x.section_id, x.label, x.starts, x.ends
    into v_target
    from private.attendance_sessions(v_uid, v_today) x
   where v_kst between x.starts - interval '30 minutes' and x.ends
     and not exists (
       select 1 from public.attendance_stamps st
        where st.student_id = v_uid and st.section_id = x.section_id and st.class_date = v_today)
   order by x.starts
   limit 1;
  if not found then
    select x.label into v_label
      from private.attendance_sessions(v_uid, v_today) x
      join public.attendance_stamps st on st.student_id = v_uid and st.section_id = x.section_id and st.class_date = v_today
     where v_kst between x.starts - interval '30 minutes' and x.ends + interval '30 minutes'
     limit 1;
    if v_label is not null then
      return jsonb_build_object('action', 'already_done', 'label', v_label);
    end if;
    select min(x.starts) into v_next
      from private.attendance_sessions(v_uid, v_today) x
     where x.starts - interval '30 minutes' > v_kst;
    if v_next is not null then
      return jsonb_build_object('action', 'too_early', 'opens', to_char(v_next - interval '30 minutes', 'HH24:MI'));
    end if;
    return jsonb_build_object('action', 'class_over');
  end if;

  v_late := v_kst > v_target.starts + interval '7 minutes';
  insert into public.attendance_stamps (student_id, section_id, class_date, status, check_in_at, late, method)
  values (v_uid, v_target.section_id, v_today, 'in', v_now, v_late, v_method)
  on conflict (student_id, section_id, class_date) do nothing
  returning id into v_id;
  if v_id is null then
    return jsonb_build_object('action', 'already_done', 'label', v_target.label);
  end if;
  insert into public.attendance_events (student_id, section_id, class_date, kind, method, result)
  values (v_uid, v_target.section_id, v_today, 'enter', v_method, case when v_late then 'late' else 'check_in' end);

  return jsonb_build_object('action', 'check_in', 'label', v_target.label, 'at', to_char(v_kst, 'HH24:MI'),
                            'late', v_late, 'starts', to_char(v_target.starts, 'HH24:MI'), 'ends', to_char(v_target.ends, 'HH24:MI'));
end;
$$;

comment on function public.attendance_scan(text, text) is
  'QR·코드로 입실/퇴실. 토큰(2분)·배정·시각을 서버가 판정한다. 규칙: 시작 30분 전부터, 7분 뒤 지각, 30분 뒤부터 퇴실, 끝나고 30분까지';

-- ─── 6. 강사·조교가 정한다: 출석 인정 · 결석 · 되돌리기 ─────────────────────
create or replace function public.attendance_set(p_student uuid, p_section bigint, p_date date, p_status text, p_note text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_note text := nullif(btrim(coalesce(p_note, '')), '');
begin
  if not private.is_crew() then
    raise exception 'forbidden';
  end if;
  if p_status not in ('manual', 'absent', 'clear') then
    raise exception 'bad_status';
  end if;
  -- 사유는 꼭 적는다 (나중에 "찍혔다가 사라졌다" 를 가릴 근거 — 첫토익 15)
  if p_status <> 'clear' and (v_note is null or char_length(v_note) > 200) then
    raise exception 'note_required';
  end if;
  if not exists (select 1 from public.enrollments e where e.student_id = p_student and e.section_id = p_section)
     or not exists (select 1 from public.session_dates d where d.section_id = p_section and d.date = p_date) then
    raise exception 'not_in_section';
  end if;

  if p_status = 'clear' then
    delete from public.attendance_stamps where student_id = p_student and section_id = p_section and class_date = p_date;
  else
    insert into public.attendance_stamps (student_id, section_id, class_date, status, method, late, decided_by, decided_note)
    values (p_student, p_section, p_date, p_status, 'manual', false, (select auth.uid()), v_note)
    on conflict (student_id, section_id, class_date) do update
       set status       = excluded.status,
           late         = false,   -- 출석 인정·결석은 지각 표시를 지운다
           decided_by   = excluded.decided_by,
           decided_note = excluded.decided_note,
           updated_at   = now();
  end if;

  insert into public.attendance_events (student_id, section_id, class_date, kind, method, result, actor_id, note)
  values (p_student, p_section, p_date, 'manual', 'manual', p_status, (select auth.uid()), v_note);
  return true;
end;
$$;

-- ─── 7. 날짜별 명단 (강사·관리자·조교) ─────────────────────────────────────
create or replace function public.attendance_roster(p_date date)
returns table (
  section_id bigint, course_name text, target_score int, track text, time_block text,
  student_id uuid, student_name text, phone text, tester boolean,
  status text, check_in_at timestamptz, check_out_at timestamptz, late boolean, decided_note text, decided_by_name text
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not private.is_crew() then
    raise exception 'forbidden';
  end if;
  return query
  select s.id, c.name, c.target_score, s.track, s.time_block,
         p.id, p.name, p.phone,
         (p.test_role is not null or p.role in ('instructor', 'admin', 'assistant')),
         st.status, st.check_in_at, st.check_out_at, coalesce(st.late, false), st.decided_note, dp.name
    from public.session_dates d
    join public.class_sections s on s.id = d.section_id
    join public.courses c on c.id = s.course_id
    join public.enrollments e on e.section_id = s.id and e.status = 'active' and e.mode = 'onsite'
    join public.enrollment_orders o on o.id = e.order_id
     and o.status in ('active', 'expired') and o.activates_on <= p_date and p_date <= o.access_until
    join public.profiles p on p.id = e.student_id
    left join public.attendance_stamps st on st.student_id = p.id and st.section_id = s.id and st.class_date = p_date
    left join public.profiles dp on dp.id = st.decided_by
   where d.date = p_date
     and not s.recorded
   order by s.time_block, c.target_score, s.track, p.name;
end;
$$;

