-- QR 출석 — 입실 · 퇴실 (2026-09-21 Alan — "출석을 범위에 넣어줘. 입실과 퇴실 다 받자! 조교에게도 명단을 열어줘")
--
--   첫토익 문서 02 의 "1인 강사·작은 학원용 최소 구성" 을 따랐다:
--   * **QR 은 주소형 · 30초마다 바뀐다** — 교실 화면(/admin/attendance/qr, 강사·조교)이 `https://winnertoeic.com/attend?t=토큰` QR 과
--     6자리 코드를 띄운다. 학생은 휴대폰 기본 카메라로 찍거나(앱 안 스캐너가 필요 없다 — 사이트는 응답 헤더로 카메라를 꺼 두었다)
--     앱의 "출석" 화면에 코드를 친다. 토큰은 **지금 칸과 앞 세 칸(2분)** 만 받는다 — 단톡방에 올린 사진은 곧 쓸모가 없어진다.
--     토큰은 DB 안의 비밀(Vault attendance_qr_secret)로 만든 HMAC 이라 앱·저장소에 값이 없다.
--   * **판정은 전부 이 파일의 함수가 한다** (public.attendance_scan) — 시각은 서버 now() 만, 반·교시도 서버가 학생 배정으로 정한다.
--     학생은 표에 직접 못 쓴다 (첫토익 5.4 — 학생이 이벤트를 넣고 트리거가 도장을 만드는 구조는 우회 길이 된다).
--   * 규칙은 첫토익 값 그대로 (Alan 이 따로 정하지 않았다): 입실은 수업 시작 **30분 전 ~ 끝**, 시작 **7분 뒤**부터 지각,
--     입실하고 **30분 안** 에 다시 찍으면 "이미 입실" (연달아 찍은 것), 그 뒤에 찍으면 **퇴실** — 퇴실은 수업이 끝나고 30분까지.
--   * 대상은 **현장 수강생** 이다 — 불라방(mode = live)은 교실에 오지 않고, 저녁 화목금 인강 날(recorded)은 녹화본을 본다.
--     한 칸 = (학생, **직접 배정된 반**, 날짜). 120분 학생은 하루 한 칸이다. 회차 id 는 편성을 고치면 바뀌어 쓰지 않는다.
--   * **강사 판정은 자동 판정이 덮지 못한다** — 출석 인정·결석은 강사·조교가 사유를 적어 정하고(public.attendance_set),
--     그 뒤 학생이 찍어도 "이미 처리됨" 이다. 출석 인정은 지각 표시를 지운다 (첫토익 11).
--   * 조교에게도 연다 (Alan). 명단·QR 화면·출석 인정/결석 모두 crew.
-- ============================================================================

-- ─── 1. 출석 도장 (한 칸 = 학생 · 반 · 날짜) ──────────────────────────────
create table if not exists public.attendance_stamps (
  id           bigint generated by default as identity primary key,
  student_id   uuid not null references public.profiles (id) on delete cascade,
  section_id   bigint not null references public.class_sections (id) on delete cascade,
  class_date   date not null,
  status       text not null check (status in ('in', 'out', 'manual', 'absent')),
  check_in_at  timestamptz,
  check_out_at timestamptz,
  late         boolean not null default false,
  method       text check (method is null or method in ('qr', 'code', 'manual')),
  decided_by   uuid references public.profiles (id) on delete set null,
  decided_note text check (decided_note is null or char_length(decided_note) <= 200),
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  unique (student_id, section_id, class_date)
);

create index if not exists attendance_stamps_date_idx on public.attendance_stamps (class_date, section_id);

comment on table public.attendance_stamps is
  'QR 출석 (2026-09-21). status: in(입실만) · out(입실+퇴실 = 출석) · manual(강사 출석 인정) · absent(강사 결석 처리)';

-- ─── 2. 기록 (쌓기만) — 부정 여부를 나중에 볼 근거, 틀린 코드 연타 막기 ───
create table if not exists public.attendance_events (
  id         bigint generated by default as identity primary key,
  student_id uuid references public.profiles (id) on delete cascade,
  section_id bigint references public.class_sections (id) on delete set null,
  class_date date,
  kind       text not null check (kind in ('enter', 'exit', 'manual', 'reject')),
  method     text,
  result     text not null,
  actor_id   uuid references public.profiles (id) on delete set null,
  note       text,
  created_at timestamptz not null default now()
);

create index if not exists attendance_events_student_idx on public.attendance_events (student_id, created_at desc);

grant select on public.attendance_stamps, public.attendance_events to authenticated;
grant all on public.attendance_stamps, public.attendance_events to service_role;

