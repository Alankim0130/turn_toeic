-- 수업자료실 공지 — 파일 · 링크 (2026-10-13 Alan — 공지 고치기 화면을 보여 주며 "공지사항에서도 파일올리기 등등 다 할 수 있도록 부탁해").
--
--   * 공지 한 편 = 제목 + 본문(서식 · 사진) + **파일 0 ~ 20개 + 링크 0 ~ 20개** — 수업자료실 자료(class_materials)와 같은 꼴.
--     파일 수 · 크기 상한(20개 · 50MB)은 자료와 같이 폼과 서버 액션이 본다.
--   * 파일은 새 표 class_notice_files (class_material_files 와 같은 꼴). 조회 = **부모 공지가 보이는 사람** (class_notices 조회 정책 그대로 —
--     학생은 올라가 있고(published) · 내 범위이고 · 수강 중인 공지만, 강사·관리자는 전부). 쓰기는 강사·관리자.
--   * 파일 자체는 저장소 class-materials 버킷의 notices/ 폴더에 둔다. 공지 사진 버킷(class-notices)은 10MB · 그림만이라 PDF · 한글 · 음원을 못 받고,
--     그 버킷을 넓히면 본문 사진의 막이 함께 풀린다. class-materials 는 50MB · 형식 제한 없음이고 쓰기는 이미 강사·관리자만이다.
--     → 그 버킷의 조회 정책에 "보이는 공지 파일 행이 있으면" 갈래를 더한다 — 남의 범위 · 내린 공지의 파일은 서명 URL 도 못 만든다.
--     파일 행의 경로는 notices/ 아래만 받는다 (check) — 공지 파일 행이 수업자료 파일(아직 안 열린 회차)을 가리켜 미리 열어 버리지 못하게.
--   * 링크는 class_notices.links(jsonb) — 수업자료실 링크와 같은 check(private.class_material_links_ok, 20261006143000).
--   * 새 표 = RLS + 정책 + grant 를 이 파일 하나에 (CLAUDE.md 보안 점검). 두 번 돌아도 된다 (if not exists · drop … if exists).
-- ============================================================================

create table if not exists public.class_notice_files (
  id           bigint generated by default as identity primary key,
  notice_id    bigint not null references public.class_notices (id) on delete cascade,
  file_path    text not null unique check (file_path like 'notices/%' and position('..' in file_path) = 0),  -- storage: class-materials/notices/…
  file_name    text not null check (char_length(file_name) between 1 and 200),
  file_size    bigint check (file_size is null or file_size >= 0),
  content_type text,
  sort_order   int not null default 0,
  created_at   timestamptz not null default now()
);

comment on table public.class_notice_files is
  '수업자료실 공지의 첨부 파일 (2026-10-13) — 공지(class_notices) 하나에 0 ~ N개, 저장소 class-materials/notices/…. 그 공지가 보이는 사람이 본다, 쓰기는 강사·관리자';

create index if not exists class_notice_files_notice_idx on public.class_notice_files (notice_id, sort_order, id);

alter table public.class_notice_files enable row level security;

grant select, insert, update, delete on public.class_notice_files to authenticated;
grant all on public.class_notice_files to service_role;

-- 조회 = 부모 공지가 보이는 사람 — 하위 조회도 class_notices 의 RLS 를 거친다 (class_material_files 와 같은 꼴)
drop policy if exists "class_notice_files: 공지가 보이는 사람 조회" on public.class_notice_files;
create policy "class_notice_files: 공지가 보이는 사람 조회" on public.class_notice_files
  for select to authenticated
  using (exists (select 1 from public.class_notices n where n.id = class_notice_files.notice_id));
drop policy if exists "class_notice_files: 스태프 등록" on public.class_notice_files;
create policy "class_notice_files: 스태프 등록" on public.class_notice_files
  for insert to authenticated with check ((select private.is_staff()));
drop policy if exists "class_notice_files: 스태프 수정" on public.class_notice_files;
create policy "class_notice_files: 스태프 수정" on public.class_notice_files
  for update to authenticated using ((select private.is_staff())) with check ((select private.is_staff()));
drop policy if exists "class_notice_files: 스태프 삭제" on public.class_notice_files;
create policy "class_notice_files: 스태프 삭제" on public.class_notice_files
  for delete to authenticated using ((select private.is_staff()));

-- ─── 링크 ───────────────────────────────────────────────────────────────────
alter table public.class_notices add column if not exists links jsonb not null default '[]'::jsonb;

alter table public.class_notices drop constraint if exists class_notices_links_check;
alter table public.class_notices add constraint class_notices_links_check check (private.class_material_links_ok(links));

comment on column public.class_notices.links is
  '링크 0 ~ 20개 (2026-10-13) — [{"url": "https://…", "label": 이름|null}]. 수업자료실 링크와 같은 check. 유튜브 영상은 학생 공지 페이지에서 바로 재생, 그 밖은 새 창';
comment on table public.class_notices is
  '수업자료실 공지 (2026-10-05) — 범위 levels × subjects(비우면 전체) · 본문(서식 · 사진) · 링크, 파일은 class_notice_files. 학생은 올라가 있고 수강 중 + 내 과정 칸이 맞을 때, 쓰기는 강사·관리자';

-- ─── 저장소: 수업자료 파일 행 또는 공지 파일 행이 보이면 ─────────────────────────
drop policy if exists "class-materials: 자료가 보이는 사람·스태프 조회" on storage.objects;
create policy "class-materials: 자료가 보이는 사람·스태프 조회" on storage.objects
  for select to authenticated
  using (
    bucket_id = 'class-materials'
    and (
      (select private.is_staff())
      or exists (select 1 from public.class_material_files f where f.file_path = objects.name)
      or exists (select 1 from public.class_notice_files f where f.file_path = objects.name)
    )
  );
