insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('staff-board', 'staff-board', false, 50 * 1024 * 1024, null)
on conflict (id) do nothing;

-- 조회 · 올리기 = 강사 · 관리자 · 조교 (사진은 images/, 첨부 파일은 files/ 에만). 지우기 = 올린 사람 · 강사 · 관리자
drop policy if exists "staff-board: 직원 조회" on storage.objects;
create policy "staff-board: 직원 조회" on storage.objects
  for select to authenticated
  using (bucket_id = 'staff-board' and (select private.is_crew()));
drop policy if exists "staff-board: 직원 올리기" on storage.objects;
create policy "staff-board: 직원 올리기" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'staff-board' and (select private.is_crew()) and (storage.foldername(name))[1] in ('images', 'files'));
drop policy if exists "staff-board: 올린 사람·강사·관리자 지우기" on storage.objects;
create policy "staff-board: 올린 사람·강사·관리자 지우기" on storage.objects
  for delete to authenticated
  using (bucket_id = 'staff-board' and (select private.is_crew()) and ((select private.is_staff()) or owner_id = (select auth.uid())::text));
