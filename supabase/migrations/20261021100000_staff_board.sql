-- 직원 게시판 (2026-10-21 Alan — "관리자모드에서 직원들만 사용할 수 있는 게시판을 하나 만들어주면 좋겠어.
--   게시물 올리는건 우리가 기존에 작업했던 워드처럼 쓸 수 있는 기능을 그대로 해줘." → 물음에 "조교도 읽고 쓰기" · "글만 올리기"(댓글 없음))
--
--   * 읽기 · 쓰기 = 강사 · 관리자 · 조교 (private.is_crew()). 학생 · 회원 · 졸업생에게는 행이 하나도 보이지 않는다.
--     테스트 등급을 켠 강사 · 관리자도 그동안은 학생으로 보인다 (private.user_role — 다른 관리자 화면과 같다).
--   * 고치기 = 글쓴이만. 지우기 = 글쓴이와 강사 · 관리자 (private.is_staff()).
--   * 글쓴이 id · 이름 · 시각은 트리거가 넣는다 — 화면이 보낸 값을 믿지 않는다 (남의 이름으로 글을 올리지 못하게, handover_checks 와 같은 규칙).
--     authenticated 는 제목 · 본문 · 링크 칸만 넣고 고친다 (칸 단위 grant). 조교는 profiles 를 못 읽으므로 이름은 author_name 에 박아 둔다.
--   * 본문 = 수업자료실 공지와 같은 서식 글(5만 자) · 사진은 [img=images/…] — 버킷 staff-board 의 images/ 폴더.
--     첨부 파일 0 ~ 20개는 staff_post_files (같은 버킷의 files/ 폴더) · 링크 0 ~ 20개는 links (수업자료실 링크와 같은 check).
--   * 저장소 staff-board (private, 50MB · 형식 제한 없음 — 공지 첨부 파일과 같다) — 조회 · 올리기는 강사 · 관리자 · 조교,
--     지우기는 올린 사람(owner_id)과 강사 · 관리자 (고치면서 뺀 사진 · 파일, 지운 글의 사진 · 파일).
--   * 계정을 합치면(merged_into) 옛 계정의 글은 남길 계정의 글이 된다 — 합친 뒤에도 고칠 수 있게.
--   * 새 표 = RLS + 정책 + grant 를 이 파일 하나에 (CLAUDE.md 보안 점검). 두 번 돌아도 된다 (if not exists · drop … if exists).
-- ============================================================================

create table if not exists public.staff_posts (
  id          bigint generated by default as identity primary key,
  title       text not null check (char_length(title) between 1 and 100),
  body        text not null default '' check (char_length(body) <= 50000),
  links       jsonb not null default '[]'::jsonb constraint staff_posts_links_check check (private.class_material_links_ok(links)),
  author_id   uuid references public.profiles (id) on delete set null,
  author_name text check (author_name is null or char_length(author_name) <= 40),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

comment on table public.staff_posts is
  '직원 게시판 (2026-10-21) — 강사 · 관리자 · 조교만 읽고 쓴다. 고치기는 글쓴이, 지우기는 글쓴이와 강사 · 관리자. 사진은 staff-board/images/, 파일은 staff_post_files';

create index if not exists staff_posts_created_idx on public.staff_posts (created_at desc, id desc);
create index if not exists staff_posts_author_idx on public.staff_posts (author_id);

-- 넣을 때 글쓴이 · 시각을 채우고, 고칠 때는 제목 · 본문 · 링크가 바뀌었을 때만 고친 시각을 올린다
create or replace function private.tg_staff_posts_stamp()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    new.author_id := auth.uid();
    new.author_name := left(private.my_profile_name(), 40);
    new.created_at := now();
    new.updated_at := now();
  elsif new.title is distinct from old.title or new.body is distinct from old.body or new.links is distinct from old.links then
    new.updated_at := now();
  end if;
  return new;
end;
$$;

revoke execute on function private.tg_staff_posts_stamp() from public, anon, authenticated;

drop trigger if exists staff_posts_stamp on public.staff_posts;
create trigger staff_posts_stamp
  before insert or update on public.staff_posts
  for each row execute function private.tg_staff_posts_stamp();

alter table public.staff_posts enable row level security;

-- 넣고 고칠 때는 제목 · 본문 · 링크만 — 글쓴이 · 시각은 위 트리거가 채운다
grant select, delete on public.staff_posts to authenticated;
grant insert (title, body, links), update (title, body, links) on public.staff_posts to authenticated;
grant all on public.staff_posts to service_role;

drop policy if exists "staff_posts: 직원 조회" on public.staff_posts;
create policy "staff_posts: 직원 조회" on public.staff_posts
  for select to authenticated using ((select private.is_crew()));
drop policy if exists "staff_posts: 직원 글쓰기" on public.staff_posts;
create policy "staff_posts: 직원 글쓰기" on public.staff_posts
  for insert to authenticated with check ((select private.is_crew()) and author_id = (select auth.uid()));
drop policy if exists "staff_posts: 글쓴이 고치기" on public.staff_posts;
create policy "staff_posts: 글쓴이 고치기" on public.staff_posts
  for update to authenticated
  using ((select private.is_crew()) and author_id = (select auth.uid()))
  with check ((select private.is_crew()) and author_id = (select auth.uid()));
drop policy if exists "staff_posts: 글쓴이·강사·관리자 지우기" on public.staff_posts;
create policy "staff_posts: 글쓴이·강사·관리자 지우기" on public.staff_posts
  for delete to authenticated
  using ((select private.is_staff()) or ((select private.is_crew()) and author_id = (select auth.uid())));

-- ─── 첨부 파일 ──────────────────────────────────────────────────────────────
create table if not exists public.staff_post_files (
  id           bigint generated by default as identity primary key,
  post_id      bigint not null references public.staff_posts (id) on delete cascade,
  file_path    text not null unique check (file_path like 'files/%' and position('..' in file_path) = 0),  -- storage: staff-board/files/…
  file_name    text not null check (char_length(file_name) between 1 and 200),
  file_size    bigint check (file_size is null or file_size >= 0),
  content_type text,
  sort_order   int not null default 0,
  created_at   timestamptz not null default now()
);

comment on table public.staff_post_files is
  '직원 게시판 글의 첨부 파일 (2026-10-21) — 글 하나에 0 ~ N개, 저장소 staff-board/files/…. 그 글이 보이는 사람(강사 · 관리자 · 조교)이 본다, 넣고 고치기는 글쓴이';

create index if not exists staff_post_files_post_idx on public.staff_post_files (post_id, sort_order, id);

alter table public.staff_post_files enable row level security;

grant select, delete on public.staff_post_files to authenticated;
grant insert (post_id, file_path, file_name, file_size, content_type, sort_order), update (sort_order) on public.staff_post_files to authenticated;
grant all on public.staff_post_files to service_role;

-- 조회 = 부모 글이 보이는 사람 — 하위 조회도 staff_posts 의 RLS 를 거친다 (class_notice_files 와 같은 꼴)
drop policy if exists "staff_post_files: 글이 보이는 사람 조회" on public.staff_post_files;
create policy "staff_post_files: 글이 보이는 사람 조회" on public.staff_post_files
  for select to authenticated
  using (exists (select 1 from public.staff_posts p where p.id = staff_post_files.post_id));
drop policy if exists "staff_post_files: 글쓴이 넣기" on public.staff_post_files;
create policy "staff_post_files: 글쓴이 넣기" on public.staff_post_files
  for insert to authenticated
  with check (exists (select 1 from public.staff_posts p where p.id = staff_post_files.post_id and p.author_id = (select auth.uid())));
drop policy if exists "staff_post_files: 글쓴이 순서 고치기" on public.staff_post_files;
create policy "staff_post_files: 글쓴이 순서 고치기" on public.staff_post_files
  for update to authenticated
  using (exists (select 1 from public.staff_posts p where p.id = staff_post_files.post_id and p.author_id = (select auth.uid())))
  with check (exists (select 1 from public.staff_posts p where p.id = staff_post_files.post_id and p.author_id = (select auth.uid())));
drop policy if exists "staff_post_files: 글쓴이·강사·관리자 지우기" on public.staff_post_files;
create policy "staff_post_files: 글쓴이·강사·관리자 지우기" on public.staff_post_files
  for delete to authenticated
  using (exists (select 1 from public.staff_posts p where p.id = staff_post_files.post_id and ((select private.is_staff()) or p.author_id = (select auth.uid()))));

-- ─── 계정을 합치면 옛 계정의 글을 남길 계정으로 ──────────────────────────────────
-- private.merge_accounts 가 profiles.merged_into 를 적는 순간 — 그 함수를 고치지 않고 따라간다 (옛 계정은 로그인이 막혀 고칠 사람이 없어진다)
create or replace function private.tg_staff_posts_follow_merge()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.staff_posts set author_id = new.merged_into where author_id = new.id;
  return null;
end;
$$;

revoke execute on function private.tg_staff_posts_follow_merge() from public, anon, authenticated;

drop trigger if exists profiles_staff_posts_follow_merge on public.profiles;
create trigger profiles_staff_posts_follow_merge
  after update of merged_into on public.profiles
  for each row
  when (old.merged_into is null and new.merged_into is not null)
  execute function private.tg_staff_posts_follow_merge();

