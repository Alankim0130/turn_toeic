-- 특강 자료실 — 그 특강을 신청한 학생만 본다 (2026-10-30 Alan — "특강신청한 사람들이 특강 신청한 곳에 들어가면 볼 수 있는 자료실이 하나 있으면 좋겠어!
-- 다른사람들 말고 신청한 사람들만 보이는 자료실이야").
--
--   * 특강 하나에 자료 0 ~ N개 — 자료 하나 = 제목 + 안내(서식 글) + 파일 0 ~ 20개 + 링크 0 ~ 20개 (수업자료실 자료와 같은 꼴).
--   * 조회 = **강사 · 관리자** 또는 **그 특강을 신청한 학생**(lecture_signups 에 내 줄이 있고 그 특강이 나에게 보인다 — 특강 조회 정책은
--     그 달 반에 배정된 학생이라 종강 뒤에는 특강과 함께 닫힌다). 신청 방식(현장 · 시험지 수령 · PDF 수령 …)은 가리지 않는다 — Alan 이 "신청한 사람들" 이라고 했다.
--     강사 · 관리자의 시험 신청도 신청이지만 어차피 강사 · 관리자는 전부 본다.
--   * 쓰기는 강사 · 관리자 (특강 설정 화면 — 조교 화면이 아니다. 등급 체계 9-1: 조교 화면을 늘리려면 Alan 에게 묻는다).
--   * 파일은 새 표 special_lecture_material_files (class_material_files 와 같은 꼴). 조회 = **부모 자료가 보이는 사람**.
--     파일 자체는 저장소 class-materials 버킷의 lectures/ 폴더 — 공지 첨부 파일(notices/)과 같은 까닭으로 새 버킷을 만들지 않는다
--     (50MB · 형식 제한 없음 · 쓰기는 이미 강사 · 관리자만). 파일 행의 경로는 lectures/ 아래만 받는다 (check) — 특강 파일 행이 아직 안 열린
--     회차의 수업자료 파일을 가리켜 미리 열어 버리지 못하게. 그 버킷의 조회 정책에 "보이는 특강 자료 파일 행이 있으면" 갈래를 더한다.
--   * 링크는 links(jsonb) — 수업자료실 링크와 같은 check(private.class_material_links_ok, 20261006143000).
--   * 특강을 달력에서 빼면 자료 · 파일 행은 함께 지워진다 (on delete cascade) — 저장소 파일은 서버 액션(saveTermSchedule)이 그 전에 읽어 두고 지운다.
--   * 새 표 = RLS + 정책 + grant 를 이 파일 하나에 (CLAUDE.md 보안 점검). 두 번 돌아도 된다 (if not exists · drop … if exists).
-- ============================================================================

create table if not exists public.special_lecture_materials (
  id          bigint generated by default as identity primary key,
  lecture_id  bigint not null references public.special_lectures (id) on delete cascade,
  title       text not null check (char_length(title) between 1 and 100),
  note        text check (note is null or char_length(note) <= 50000),
  links       jsonb not null default '[]'::jsonb check (private.class_material_links_ok(links)),
  sort_order  int not null default 0,
  uploaded_by uuid references public.profiles (id) on delete set null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

comment on table public.special_lecture_materials is
  '특강 자료실 (2026-10-30) — 특강 하나에 자료 0 ~ N개(제목 · 안내 · 링크, 파일은 special_lecture_material_files). 그 특강을 신청한 학생과 강사 · 관리자만 본다, 쓰기는 강사 · 관리자';

create index if not exists special_lecture_materials_lecture_idx on public.special_lecture_materials (lecture_id, sort_order, created_at, id);

alter table public.special_lecture_materials enable row level security;

grant select, insert, update, delete on public.special_lecture_materials to authenticated;
grant all on public.special_lecture_materials to service_role;

-- 조회: 스태프 확인을 맨 앞에 (화면 전환 속도 4) → 내가 신청한 특강이고 그 특강이 나에게 보일 때.
-- 하위 조회(lecture_signups · special_lectures)도 그 표의 RLS 를 거친다 — 학생은 제 신청과 제 기수의 특강만 본다
drop policy if exists "special_lecture_materials: 신청자·스태프 조회" on public.special_lecture_materials;
create policy "special_lecture_materials: 신청자·스태프 조회" on public.special_lecture_materials
  for select to authenticated
  using (
    (select private.is_staff())
    or (
      exists (
        select 1 from public.lecture_signups s
         where s.lecture_id = special_lecture_materials.lecture_id
           and s.user_id = (select auth.uid())
      )
      and exists (select 1 from public.special_lectures l where l.id = special_lecture_materials.lecture_id)
    )
  );
drop policy if exists "special_lecture_materials: 스태프 등록" on public.special_lecture_materials;
create policy "special_lecture_materials: 스태프 등록" on public.special_lecture_materials
  for insert to authenticated with check ((select private.is_staff()));
drop policy if exists "special_lecture_materials: 스태프 수정" on public.special_lecture_materials;
create policy "special_lecture_materials: 스태프 수정" on public.special_lecture_materials
  for update to authenticated using ((select private.is_staff())) with check ((select private.is_staff()));
drop policy if exists "special_lecture_materials: 스태프 삭제" on public.special_lecture_materials;
create policy "special_lecture_materials: 스태프 삭제" on public.special_lecture_materials
  for delete to authenticated using ((select private.is_staff()));

-- ─── 파일 ───────────────────────────────────────────────────────────────────
create table if not exists public.special_lecture_material_files (
  id           bigint generated by default as identity primary key,
  material_id  bigint not null references public.special_lecture_materials (id) on delete cascade,
  file_path    text not null unique check (file_path like 'lectures/%' and position('..' in file_path) = 0),  -- storage: class-materials/lectures/…
  file_name    text not null check (char_length(file_name) between 1 and 200),
  file_size    bigint check (file_size is null or file_size >= 0),
  content_type text,
  sort_order   int not null default 0,
  created_at   timestamptz not null default now()
);

comment on table public.special_lecture_material_files is
  '특강 자료의 파일 (2026-10-30) — 자료(special_lecture_materials) 하나에 0 ~ N개, 저장소 class-materials/lectures/…. 그 자료가 보이는 사람이 본다, 쓰기는 강사 · 관리자';

create index if not exists special_lecture_material_files_material_idx on public.special_lecture_material_files (material_id, sort_order, id);

alter table public.special_lecture_material_files enable row level security;

grant select, insert, update, delete on public.special_lecture_material_files to authenticated;
grant all on public.special_lecture_material_files to service_role;

-- 조회 = 부모 자료가 보이는 사람 — 하위 조회도 special_lecture_materials 의 RLS 를 거친다
drop policy if exists "special_lecture_material_files: 자료가 보이는 사람 조회" on public.special_lecture_material_files;
create policy "special_lecture_material_files: 자료가 보이는 사람 조회" on public.special_lecture_material_files
  for select to authenticated
  using (exists (select 1 from public.special_lecture_materials m where m.id = special_lecture_material_files.material_id));
drop policy if exists "special_lecture_material_files: 스태프 등록" on public.special_lecture_material_files;
create policy "special_lecture_material_files: 스태프 등록" on public.special_lecture_material_files
  for insert to authenticated with check ((select private.is_staff()));
drop policy if exists "special_lecture_material_files: 스태프 수정" on public.special_lecture_material_files;
create policy "special_lecture_material_files: 스태프 수정" on public.special_lecture_material_files
  for update to authenticated using ((select private.is_staff())) with check ((select private.is_staff()));
drop policy if exists "special_lecture_material_files: 스태프 삭제" on public.special_lecture_material_files;
create policy "special_lecture_material_files: 스태프 삭제" on public.special_lecture_material_files
  for delete to authenticated using ((select private.is_staff()));

-- ─── 저장소: 수업자료 파일 행 · 공지 파일 행 · 특강 자료 파일 행 중 하나가 보이면 ────
drop policy if exists "class-materials: 자료가 보이는 사람·스태프 조회" on storage.objects;
create policy "class-materials: 자료가 보이는 사람·스태프 조회" on storage.objects
  for select to authenticated
  using (
    bucket_id = 'class-materials'
    and (
      (select private.is_staff())
      or exists (select 1 from public.class_material_files f where f.file_path = objects.name)
      or exists (select 1 from public.class_notice_files f where f.file_path = objects.name)
      or exists (select 1 from public.special_lecture_material_files f where f.file_path = objects.name)
    )
  );
