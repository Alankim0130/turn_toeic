-- 원하는 과정의 자료를 오픈하는 형태로 진행을 하고 싶어. 폴더를 여러개 만들고 한 폴더를 클릭해서 수업자료를 여러개 만들어 놓고, 그걸 몇월 수업자료로
-- 사용하고 싶다고 하면 그 자료들이 학생들에게 오픈되면 좋겠어. 기존에 날짜별 오픈시스템도 그대로 적용되면 좋겠어. 그리고 RC 강사게시판과 LC강사 게시판을 분류"
-- → 고른 것: 자료마다 회차 · 달 + 과정(A/B)으로 연다 · **그 달 그 과정은 폴더 자료만** · 폴더 더하기 · 위치 · 이름 바꾸기.
--
--   * teacher_folders      — 폴더. 과목(rc | lc)이 RC 강사게시판 · LC 강사게시판을 가른다. 강사 · 관리자만 본다.
--   * teacher_folder_items — 폴더 안 자료. 자료 하나 = 회차 + 제목 + 안내(서식 글) + 링크 (수업자료실 자료와 같은 꼴, 레벨 · 과정은 쓰는 달이 정한다).
--   * teacher_folder_files — 자료의 파일 0 ~ N개. 저장소 class-materials 의 teacher/ 폴더 (공지 notices/ · 특강 lectures/ 와 같은 까닭으로 새 버킷 없음).
--   * teacher_folder_uses  — "몇월 수업자료로 쓰기": 폴더 × 기수 × 레벨 × 과정. 과목은 폴더의 것 (복합 FK 로 맞춘다).
--                            한 달 · 레벨 · 과목 · 과정 칸에는 폴더 하나 (unique).
--
-- 학생에게 열리는 규칙 — 화면이 아니라 DB 가 막는다:
--   * 폴더 자료 = 그 폴더를 쓰는 (기수 · 레벨 · 과목 · 과정) 칸을 쓰는 **내 반**의 그 회차 수업일(KST)이 오늘이거나 지났다 → private.my_open_term_rounds()
--     (my_open_rounds 와 같은 규칙에 기수만 더했다 — 같은 과정 글자가 달마다 다른 시간대를 돌기 때문이다).
--   * **그 달 그 칸은 폴더 자료만** — 기존 수업자료실(class_materials)은 폴더를 쓰지 않는 칸의 회차만 연다 → private.my_open_class_rounds().
--     LC 음원은 my_open_rounds 그대로 (폴더와 상관없다).
--   * 파일 행은 부모 자료가 보이는 사람, 저장소는 그 파일 행이 보이는 사람.
-- 새 표 = RLS + 정책 + grant 를 이 파일 하나에 (CLAUDE.md 보안). 조회 정책은 스태프 확인을 맨 앞에. 두 번 돌아도 된다.
