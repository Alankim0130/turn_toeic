-- ─── 학생의 칸 · 회차 (기수까지) ───────────────────────────────────────────────
-- 내 기수 · 과정 칸 'term:level:subject:set' — private.my_round_cells 에 기수를 더한 것
create or replace function private.my_term_cells()
returns text[]
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(array_agg(distinct format('%s:%s:%s:%s', s.term_id, c.target_score, sub.subject, s.book_set)), '{}')
  from unnest(public.my_section_ids()) as m(id)
  join public.class_sections s on s.id = m.id
  join public.courses c on c.id = s.course_id
  cross join lateral unnest(case when s.subject is null then array['rc', 'lc'] else array[s.subject] end) as sub(subject)
  where (select private.user_role()) in ('student', 'instructor', 'admin', 'assistant')
    and c.target_score is not null
    and s.book_set is not null
$$;
comment on function private.my_term_cells() is
  '내 기수 · 과정 칸 term:level:subject:set (2026-11-03) — 강사 자료 게시판의 "몇월에 쓰기" 조회. my_round_cells 에 기수를 더했다';

-- 열린 회차 'term:level:subject:set:seq' — private.my_open_rounds 에 기수를 더한 것 (폴더 자료)
create or replace function private.my_open_term_rounds()
returns text[]
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(array_agg(distinct format('%s:%s:%s:%s:%s', s.term_id, c.target_score, sub.subject, s.book_set, d.seq)), '{}')
  from unnest(public.my_section_ids()) as m(id)
  join public.class_sections s on s.id = m.id
  join public.courses c on c.id = s.course_id
  join public.session_dates d on d.section_id = s.id
  cross join lateral unnest(case when s.subject is null then array['rc', 'lc'] else array[s.subject] end) as sub(subject)
  where (select private.user_role()) in ('student', 'instructor', 'admin', 'assistant')
    and c.target_score is not null
    and s.book_set is not null
    and d.date <= private.today_kst()
$$;
comment on function private.my_open_term_rounds() is
  '열린 회차 term:level:subject:set:seq (2026-11-03) — 강사 자료 게시판 폴더 자료 조회. my_open_rounds 와 같은 규칙에 기수만 더했다. 앱 splitRoundDates 와 같은 규칙';

-- 폴더를 쓰지 않는 칸의 열린 회차 'level:subject:set:seq' — 수업자료실(class_materials). **그 달 그 칸은 폴더 자료만** (Alan "그 달은 폴더 자료만")
create or replace function private.my_open_class_rounds()
returns text[]
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(array_agg(distinct format('%s:%s:%s:%s', c.target_score, sub.subject, s.book_set, d.seq)), '{}')
  from unnest(public.my_section_ids()) as m(id)
  join public.class_sections s on s.id = m.id
  join public.courses c on c.id = s.course_id
  join public.session_dates d on d.section_id = s.id
  cross join lateral unnest(case when s.subject is null then array['rc', 'lc'] else array[s.subject] end) as sub(subject)
  where (select private.user_role()) in ('student', 'instructor', 'admin', 'assistant')
    and c.target_score is not null
    and s.book_set is not null
    and d.date <= private.today_kst()
    and not exists (
      select 1 from public.teacher_folder_uses u
       where u.term_id = s.term_id and u.level = c.target_score and u.subject = sub.subject and u.book_set = s.book_set
    )
$$;
comment on function private.my_open_class_rounds() is
  '수업자료실 열린 회차 level:subject:set:seq (2026-11-03) — my_open_rounds 에서 강사 자료 게시판 폴더를 쓰는 (기수 · 칸)을 뺀 것. 앱 splitRoundDates 와 같은 규칙';

revoke all on function private.my_term_cells() from public, anon;
revoke all on function private.my_open_term_rounds() from public, anon;
revoke all on function private.my_open_class_rounds() from public, anon;
grant execute on function private.my_term_cells() to authenticated, service_role;
grant execute on function private.my_open_term_rounds() to authenticated, service_role;
grant execute on function private.my_open_class_rounds() to authenticated, service_role;

